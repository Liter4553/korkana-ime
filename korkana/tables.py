# ---------------------------------------------------------------- 히라가나 <-> 가타카나
_HIRA_START, _HIRA_END, _KATA_OFFSET = 0x3041, 0x3096, 0x60


def to_katakana(text: str) -> str:
    return "".join(
        chr(ord(ch) + _KATA_OFFSET) if _HIRA_START <= ord(ch) <= _HIRA_END else ch
        for ch in text
    )
